<?php
/**
 * Настройки подключения к базе данных MySQL.
 * OpenServer (локально): host=localhost, user=root, пароль обычно пустой, база — создайте сами (например gpu_site).
 * Beget: хост localhost, имя БД/пользователя/пароль смотрите в панели Beget -> "Базы данных MySQL".
 */
return [
    // ВАЖНО для OpenServer на Windows: MySQL слушает TCP-порт 3306, а localhost может
    // резолвиться в IPv6 ::1, который MySQL не принимает -> ошибка 2002. Поэтому 127.0.0.1.
    // На Beget тоже оставляем 127.0.0.1 (или localhost — оба работают).
    // Если 127.0.0.1 не работает — раскомментируйте строку с портом 3307:
    // 'host' => '127.0.0.1:3307',
    // Примечание: api/db.php при неудаче сам пробует дополнительные локальные
    // адреса (127.0.1.31, localhost), поэтому в типовых сборках OpenServer этот
    // пункт можно не менять.
    'host' => '127.0.0.1',
    'user' => 'root',            // на Beget замените на вашего пользователя (обычно логин_имя)
    'pass' => '',                // на Beget — пароль от базы из панели
    'db'   => 'gpu_site',        // имя базы (на Beget будет вида username_gpu_site)
    'charset' => 'utf8mb4',
];
